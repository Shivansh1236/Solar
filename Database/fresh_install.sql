-- Solar Power Generation Prediction
-- Fresh Supabase PostgreSQL schema for the current two-plant application.
-- Run this file ONCE in the SQL Editor of a brand-new Supabase project.
-- Do NOT run this on an existing project that already has these tables.
-- This script creates the final schema directly; do not run the incremental
-- migrations in migrations/ after running this fresh-install script.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Manual prediction history
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.prediction_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    plant_id SMALLINT NOT NULL CHECK (plant_id IN (1, 2)),
    model_name TEXT NOT NULL,
    source_key INTEGER NOT NULL,
    ambient_temperature DOUBLE PRECISION NOT NULL,
    module_temperature DOUBLE PRECISION NOT NULL,
    irradiation DOUBLE PRECISION NOT NULL,
    hour SMALLINT NOT NULL,
    day SMALLINT NOT NULL,
    month SMALLINT NOT NULL,
    weekday SMALLINT NOT NULL,
    is_weekend SMALLINT NOT NULL,
    predicted_ac_power DOUBLE PRECISION NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_prediction_history_created_at
    ON public.prediction_history (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_prediction_history_plant_created_at
    ON public.prediction_history (plant_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- 2. Analysis sessions
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.analysis_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    location_name TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    timezone TEXT NOT NULL,
    interval_minutes INTEGER NOT NULL
        CHECK (interval_minutes IN (1, 5, 10, 15, 30, 60)),
    max_readings INTEGER NULL CHECK (max_readings IS NULL OR max_readings >= 1),
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'stopped', 'completed', 'interrupted')),
    module_temperature_mode TEXT NOT NULL DEFAULT 'auto'
        CHECK (module_temperature_mode IN ('auto', 'manual')),
    manual_module_temperature DOUBLE PRECISION NULL,
    source_key_mode TEXT NOT NULL DEFAULT 'default'
        CHECK (source_key_mode IN ('default', 'manual')),
    manual_source_key INTEGER NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    stopped_at TIMESTAMPTZ NULL,
    last_activity_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    analysis_mode TEXT NOT NULL DEFAULT 'comparison',
    selected_plant_id SMALLINT NULL,
    CONSTRAINT analysis_sessions_module_temperature_check CHECK (
        (module_temperature_mode = 'auto' AND manual_module_temperature IS NULL)
        OR
        (module_temperature_mode = 'manual' AND manual_module_temperature IS NOT NULL)
    ),
    CONSTRAINT analysis_sessions_source_key_check CHECK (
        (source_key_mode = 'default' AND manual_source_key IS NULL)
        OR
        (source_key_mode = 'manual' AND manual_source_key IS NOT NULL AND manual_source_key >= 0)
    ),
    CONSTRAINT analysis_sessions_analysis_mode_check CHECK (
        (analysis_mode = 'comparison' AND selected_plant_id IS NULL)
        OR
        (analysis_mode = 'single' AND selected_plant_id IN (1, 2))
    )
);

CREATE INDEX IF NOT EXISTS idx_analysis_sessions_started_at
    ON public.analysis_sessions (started_at DESC);

CREATE INDEX IF NOT EXISTS idx_analysis_sessions_status
    ON public.analysis_sessions (status);

-- ---------------------------------------------------------------------------
-- 3. Analysis readings
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.analysis_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL
        REFERENCES public.analysis_sessions (id) ON DELETE CASCADE,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Open-Meteo local wall-clock timestamp; intentionally without timezone.
    weather_time_local TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    source_key INTEGER NOT NULL,
    ambient_temperature DOUBLE PRECISION NOT NULL,
    module_temperature DOUBLE PRECISION NOT NULL,
    shortwave_radiation_wm2 DOUBLE PRECISION NOT NULL,
    irradiation DOUBLE PRECISION NOT NULL,
    hour SMALLINT NOT NULL,
    day SMALLINT NOT NULL,
    month SMALLINT NOT NULL,
    weekday SMALLINT NOT NULL,
    is_weekend SMALLINT NOT NULL,
    -- Legacy compatibility field retained for older reports and API clients.
    predicted_ac_power DOUBLE PRECISION NULL,
    plant_1_predicted_ac_power DOUBLE PRECISION NULL,
    plant_2_predicted_ac_power DOUBLE PRECISION NULL,
    plant_1_model_name TEXT NULL,
    plant_2_model_name TEXT NULL,
    CONSTRAINT analysis_readings_at_least_one_prediction CHECK (
        predicted_ac_power IS NOT NULL
        OR plant_1_predicted_ac_power IS NOT NULL
        OR plant_2_predicted_ac_power IS NOT NULL
    )
);

CREATE INDEX IF NOT EXISTS idx_analysis_readings_session_fetched_at
    ON public.analysis_readings (session_id, fetched_at ASC);

COMMIT;

